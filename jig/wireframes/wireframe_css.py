def generate_wireframe_css(design_system: DesignSystem | None = None) -> str:
    """Produce the wireframe.css content.

    With no ``design_system`` argument, returns the baseline greyscale
    stylesheet (``WIREFRAME_CSS`` constant). When a design system is
    passed, the color/spacing/type/shadow/border-radius variable values
    in the ``:root`` block are overridden from the system's tokens.
    The utility classes themselves stay identical — that's the whole
    point of the value-swap-not-stylesheet-swap transition.

    For MVP this implementation does a targeted variable substitution
    rather than re-emitting the whole file. The substitution looks for
    the ``--<token-id>: <old>;`` pattern in the baseline and rewrites
    the value when the token id matches. Token ids that aren't already
    in the baseline are appended into ``:root`` so the operator's
    extensions land in scope.
    """
    if design_system is None:
        return WIREFRAME_CSS

    css = WIREFRAME_CSS
    extras: list[str] = []

    for token in design_system.tokens.tokens:
        # Map the token id to its CSS variable name. Token ids in the
        # default set already match the variable suffixes (``color-bg``
        # → ``--color-bg``); operator-supplied tokens follow the same
        # convention by contract.
        var_name = f"--{token.id}"
        # Tokenize on ``var_name: ... ;`` to do a targeted replacement
        # without affecting the surrounding declarations.
        marker = f"{var_name}:"
        idx = css.find(marker)
        if idx == -1:
            extras.append(f"  {var_name}: {token.value};")
            continue
        end = css.find(";", idx)
        if end == -1:
            # Defensive: malformed baseline (shouldn't happen since we
            # author it ourselves). Append to extras rather than raise
            # so a single broken declaration doesn't blow up the whole
            # generator.
            extras.append(f"  {var_name}: {token.value};")
            continue
        css = css[:idx] + f"{var_name}: {token.value}" + css[end:]

    if extras:
        # Splice extras into the existing :root block just before its
        # closing brace. The baseline always has exactly one :root
        # block; this is the simplest seam we can rely on without
        # bringing in a CSS parser.
        marker = "\n}"
        # Find the end of the FIRST closing brace after ``:root {`` —
        # that's the :root block we authored. Subsequent } belong to
        # other selectors.
        root_idx = css.find(":root {")
        if root_idx != -1:
            close_idx = css.find("\n}", root_idx)
            if close_idx != -1:
                css = (
                    css[:close_idx]
                    + "\n"
                    + "\n".join(extras)
                    + css[close_idx:]
                )
    return css
