"""Canonical wireframe.css generator.

Per ``docs/visual-design/design.md`` §"The wireframe.css — static
utility layer + greyscale tokens": one hand-curated stylesheet (~200-300
lines) covering the most-used Tailwind-shaped utility names, with
implementations driven by CSS custom properties. Wireframes use the
class names; the visual outcome is greyscale because of the variable
values.

The agent never edits this file — it's generated once at VD discovery
start. The transition wireframe → bones is "swap the variable values"
not "swap the stylesheet"; for MVP we ship the wireframe-mode values
inline. The MVP scope generator takes an optional ``DesignSystem`` and
overrides the color tokens from it (so the operator-supplied tokens
land at MVP layer).
"""
from __future__ import annotations

from jig.schemas.design_system import DesignSystem

__all__ = ["WIREFRAME_CSS", "generate_wireframe_css"]


