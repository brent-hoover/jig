"""Bones-with-hostile scenario (Track H Final).

Verifies the spine recovers cleanly from the hostile persona's
contradictory + terse inputs. The full hostile-as-loop assertion (the
agent re-prompts after a refusal) requires LLM-driven turns and lands
in v2.x; this scenario's contract is "the agent doesn't crash on
hostile inputs and the spine resolves."
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from jig.sim.driver import Driver
from jig.sim.scenario import load_scenario


pytestmark = pytest.mark.sim_smoke


SCENARIO_PATH = Path(__file__).parent / "scenarios" / "bones-with-hostile.scenario.yaml"


def _seed_repo(root: Path) -> None:
    subprocess.run(
        ["git", "init", "-b", "main"], cwd=root, check=True, capture_output=True
    )
    for k, v in (
        ("user.email", "test@example.com"),
        ("user.name", "Test"),
        ("commit.gpgsign", "false"),
    ):
        subprocess.run(
            ["git", "config", k, v], cwd=root, check=True, capture_output=True
        )
    (root / "README.md").write_text("seed\n")
    subprocess.run(["git", "add", "-A"], cwd=root, check=True, capture_output=True)
    subprocess.run(
        ["git", "commit", "-m", "seed"], cwd=root, check=True, capture_output=True
    )


@pytest.mark.asyncio
async def test_hostile_scenario_passes(tmp_path: Path):
    """Spine resolves cleanly despite hostile-flavored inputs."""
    _seed_repo(tmp_path)
    scenario = load_scenario(SCENARIO_PATH)
    report = await Driver().run(scenario, project_root=tmp_path)
    assert report.passed, report.failure_summary()
